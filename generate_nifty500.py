def generate_nifty500():
    random.seed(42)  # Deterministic consistent data
    stocks = []
    
    # 1. Add predefined known stocks
    for item in NIFTY500_RAW:
        sym, name, sec, last, chg, rs = item
        # Realistic DMA alignment correlated with RS score
        dma20 = rs >= 65 if random.random() > 0.15 else rs >= 50
        dma50 = rs >= 60 if random.random() > 0.15 else rs >= 45
        dma200 = rs >= 50 if random.random() > 0.15 else rs >= 40
        high_dist = round(-1.0 * (100 - rs) * 0.25 - random.random() * 2.0, 1)
        rsi = min(88, max(28, int(rs * 0.6 + random.randint(10, 30))))
        surge = rs >= 85 and random.random() > 0.4
        
        stocks.append({
            "symbol": sym,
            "name": name,
            "sector": sec,
            "last": last,
            "changePct": chg,
            "dma20": dma20,
            "dma50": dma50,
            "dma200": dma200,
            "high52Dist": high_dist,
            "rsi": rsi,
            "volumeSurge": surge,
            "rsRating": rs
        })

    # 2. Fill remainder up to 500 with mid/small cap constituent stocks
    sectors = [
        "Capital Goods", "Financial Services", "IT", "Pharma", "Chemicals", 
        "Auto Ancillary", "Healthcare", "Consumer Durables", "Infra", "Energy", 
        "Metal", "FMCG", "Realty", "Services", "Textiles", "Defence", "Bank", "PSU Bank"
    ]

    prefixes = [
        "Bharat", "Indian", "National", "Shree", "Premier", "Apex", "Global", 
        "Supreme", "Dynamic", "Sterling", "Standard", "Orient", "Zenith", "Continental",
        "Pioneer", "United", "Precision", "Matrix", "Kaveri", "Kalyani", "Anand",
        "Vardhman", "Gokul", "Jindal", "Mahindra", "Tata", "Birla", "Bajaj"
    ]
    
    suffixes = [
        "Enterprises", "Industries", "Technologies", "Solutions", "Infra", 
        "Engineering", "Holdings", "Chemicals", "Pharma", "Specialities", "Ventures",
        "Systems", "Products", "Logistics", "Power", "Resources", "Finance"
    ]

    current_count = len(stocks)
    idx = 1
    while len(stocks) < 500:
        p = random.choice(prefixes)
        s = random.choice(suffixes)
        sym = f"{p[:4].upper()}{s[:4].upper()}{idx}"
        name = f"{p} {s} India Ltd."
        sec = random.choice(sectors)
        last = round(random.uniform(45.0, 8500.0), 2)
        chg = round(random.uniform(-3.5, 4.5), 2)
        rs = random.randint(35, 98)
        
        dma20 = rs >= 62 if random.random() > 0.15 else rs >= 50
        dma50 = rs >= 58 if random.random() > 0.15 else rs >= 45
        dma200 = rs >= 48 if random.random() > 0.15 else rs >= 40
        high_dist = round(-1.0 * (100 - rs) * 0.28 - random.random() * 2.5, 1)
        rsi = min(88, max(28, int(rs * 0.6 + random.randint(10, 30))))
        surge = rs >= 85 and random.random() > 0.5

        stocks.append({
            "symbol": sym,
            "name": name,
            "sector": sec,
            "last": last,
            "changePct": chg,
            "dma20": dma20,
            "dma50": dma50,
            "dma200": dma200,
            "high52Dist": high_dist,
            "rsi": rsi,
            "volumeSurge": surge,
            "rsRating": rs
        })
        idx += 1

    # Generate simulated Multi-Timeframe Divergence Data for all 500 stocks
    # Divergence types: Bullish, Bearish, Hidden Bullish, Hidden Bearish, None
    div_types = ["Bullish", "Bearish", "Hidden Bullish", "Hidden Bearish", "None"]
    
    for s in stocks:
        # Bias the probabilities based on RSI to make it realistic
        rsi = s["rsi"]
        
        def get_div_for_tf(timeframe_rsi):
            # 80% chance of NO divergence
            if random.random() < 0.80:
                return "None"
            
            # If oversold, highly likely to be Bullish or Hidden Bullish
            if timeframe_rsi < 40:
                return random.choices(["Bullish", "Hidden Bullish", "Bearish", "Hidden Bearish"], weights=[0.6, 0.3, 0.05, 0.05])[0]
            # If overbought, highly likely to be Bearish or Hidden Bearish
            elif timeframe_rsi > 60:
                return random.choices(["Bearish", "Hidden Bearish", "Bullish", "Hidden Bullish"], weights=[0.6, 0.3, 0.05, 0.05])[0]
            else:
                return random.choices(["Bullish", "Bearish", "Hidden Bullish", "Hidden Bearish"], weights=[0.25, 0.25, 0.25, 0.25])[0]

        # Use current RSI for 1D, and slightly perturbed RSIs for 1W and 1M
        s["divergence"] = {
            "1D": get_div_for_tf(rsi),
            "1W": get_div_for_tf(rsi + random.randint(-15, 15)),
            "1M": get_div_for_tf(rsi + random.randint(-25, 25))
        }

    with open("nifty500_stocks.json", "w", encoding="utf-8") as f:
        json.dump(stocks, f, indent=2)

    print(f"Generated {len(stocks)} Nifty 500 constituent stocks in nifty500_stocks.json")

